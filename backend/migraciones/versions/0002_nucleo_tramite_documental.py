def _por_cada_rol_con_acceso(tabla: str, sentencia: str) -> None:
    """Ejecuta `sentencia` (con `%I` para el rol) para cada rol, salvo el propietario,
    que recibió privilegios sobre `tabla` por los privilegios por defecto del esquema.

    Evita que la migración dependa del nombre del usuario de aplicación de cada
    entorno (atlas_dev_app, atlas_tests_app, …).
    """
    # `tabla` y `sentencia` son constantes de esta migración, nunca datos externos.
    op.execute(
        f"""
        DO $$
        DECLARE r record;
        BEGIN
          FOR r IN SELECT DISTINCT grantee FROM information_schema.role_table_grants
                   WHERE table_schema = 'atlas' AND table_name = '{tabla}'
                     AND grantee <> current_user
          LOOP
            EXECUTE format('{sentencia}', r.grantee);
          END LOOP;
        END $$;
        """  # noqa: S608
    )


