"""Validación humana de clasificación y campos (Figura 5.4: VALIDACION_HUMANA).

Revisión: 0006
Anterior: 0005
Trazabilidad: RF-09, RF-12, RN-02, RN-03, RN-09, §5.3.3, DO-2026-10-22-VAL, PD-04 (PD-04-008).

- Cada validación es una fila nueva e inmutable; una corrección posterior referencia la
  que reemplaza. El valor aplicable de un dato es el de la validación no reemplazada.
- Índice único parcial: una sola primera validación por (versión, clase, campo);
  `UNIQUE (reemplaza_a_id)`: de dos reemplazos simultáneos solo uno se completa.
- Un *trigger* verifica que la validación reemplazada, la sugerencia y la fuente
  correspondan a la misma versión, campo y archivo, y que el archivo esté incorporado.
- `referencia_fuente` admite fuentes indicadas por una persona (sin trabajo ni intento).
"""

